#!/usr/bin/env node
/**
 * Build database/install.sql from the live database.
 *
 * The file is the documented way to stand the project up on a new machine, so
 * it has to contain the real content - packages, portfolio, pages, posts,
 * menus, settings - not just the schema. It is generated rather than exported
 * by hand for three reasons:
 *
 *   1. Credentials. The settings table stores secrets unencrypted, so a raw
 *      export publishes the reCAPTCHA, SMTP, Google and assistant keys. Every
 *      `SECRET_KEYS` value is blanked here, keeping the row so the installer
 *      still seeds the key and the operator fills it in.
 *
 *   2. Re-import. phpMyAdmin writes a bare `CREATE TABLE` with no matching
 *      `DROP`, so its output can only ever be imported once - the second run
 *      stops at "table already exists" and leaves a half-populated database.
 *      Every table is dropped up front instead.
 *
 *   3. `sessions`. Session rows belong to one install. Seeding them elsewhere
 *      achieves nothing and puts live session ids in a public file.
 *
 *   node scripts/build-install-sql.js
 *   node scripts/build-install-sql.js --keep-sessions   # for a full local backup
 */
'use strict';

require('dotenv').config();

const fs = require('fs');
const path = require('path');

const db = require('../src/config/database');
const config = require('../src/config');
const schema = require('../src/config/settings-schema');
const { sqlValue, sqlIdent } = require('../src/utils/sql');

const OUT = path.join(__dirname, '..', 'database', 'install.sql');
const ROWS_PER_STATEMENT = 100;

/**
 * Tables whose ROWS belong to one installation and must not be seeded.
 *
 * The table itself still has to be created: MySQLSessionStore is given a table
 * name and nothing else, so a fresh install with no `sessions` table fails on
 * the first request rather than on import.
 */
const NO_DATA = new Set(['sessions']);

const keepSessions = process.argv.includes('--keep-sessions');

function stamp() {
  return new Date().toISOString().slice(0, 19).replace('T', ' ');
}

async function main() {
  const tables = (
    await db.query(
      'SELECT table_name AS name FROM information_schema.tables WHERE table_schema = DATABASE() ORDER BY table_name ASC'
    )
  ).map((row) => row.name);

  // Structure for everything; rows for everything except the transient tables.
  const schemas = tables;
  const withData = keepSessions ? tables : tables.filter((name) => !NO_DATA.has(name));
  const skipped = tables.filter((name) => !withData.includes(name));

  const out = [];

  out.push('-- WooBD.Com database install');
  out.push(`-- Generated: ${stamp()}`);
  out.push(`-- Database: ${config.db.database}`);
  out.push('--');
  out.push('-- Generated by scripts/build-install-sql.js. Do not hand-edit: the next');
  out.push('-- build overwrites it. Run that script after changing any content.');
  out.push('--');
  out.push('-- Credential values are deliberately blank. This file is committed, and the');
  out.push('-- settings table stores secrets in plain text - an export that kept them');
  out.push('-- would publish the reCAPTCHA, SMTP, Google and assistant keys. Fill them in');
  out.push('-- on Settings after importing.');
  out.push('');
  out.push('SET SQL_MODE = "NO_AUTO_VALUE_ON_ZERO";');
  out.push('SET time_zone = "+00:00";');
  out.push('SET NAMES utf8mb4;');
  out.push('');
  out.push('-- Foreign keys are checked off for the whole import. The drops below run');
  out.push('-- before any create, so the file can be imported over an existing database');
  out.push('-- as well as into an empty one.');
  out.push('SET FOREIGN_KEY_CHECKS = 0;');
  out.push('START TRANSACTION;');
  out.push('');

  // --- Drop everything first ------------------------------------------------
  out.push('-- --------------------------------------------------------');
  out.push('-- Drop, in one block, before anything is created');
  out.push('-- --------------------------------------------------------');
  out.push('');
  for (const table of schemas) {
    out.push(`DROP TABLE IF EXISTS ${sqlIdent(table)};`);
  }
  out.push('');

  // --- Schema ---------------------------------------------------------------
  for (const table of schemas) {
    const row = await db.queryOne(`SHOW CREATE TABLE ${sqlIdent(table)}`);
    const createSql = row && row['Create Table'];

    if (!createSql) {
      console.warn(`  ! no CREATE TABLE for ${table} - skipped`);
      continue;
    }

    out.push('-- --------------------------------------------------------');
    out.push(`-- Table structure for ${sqlIdent(table)}`);
    out.push('-- --------------------------------------------------------');
    out.push('');
    out.push(`${createSql};`);
    out.push('');
  }

  // --- Data -----------------------------------------------------------------
  let totalRows = 0;
  let scrubbed = 0;

  for (const table of withData) {
    const rows = await db.query(`SELECT * FROM ${sqlIdent(table)}`);

    out.push('-- --------------------------------------------------------');
    out.push(`-- Data for ${sqlIdent(table)}`);
    out.push('-- --------------------------------------------------------');
    out.push('');

    if (!rows.length) {
      out.push(`-- (no rows)`);
      out.push('');
      continue;
    }

    const columns = Object.keys(rows[0]);
    const columnList = columns.map(sqlIdent).join(', ');

    for (let i = 0; i < rows.length; i += ROWS_PER_STATEMENT) {
      const slice = rows.slice(i, i + ROWS_PER_STATEMENT);

      const tuples = slice.map((row) => {
        const values = columns.map((column) => {
          // The one place a value is ever altered. Everything else goes in
          // exactly as it is stored.
          if (table === 'settings' && column === 'setting_value' && schema.SECRET_KEYS.has(row.setting_key)) {
            if (row.setting_value) scrubbed += 1;
            return "''";
          }
          return sqlValue(row[column]);
        });

        return `(${values.join(', ')})`;
      });

      out.push(`INSERT INTO ${sqlIdent(table)} (${columnList}) VALUES`);
      out.push(tuples.join(',\n') + ';');
      out.push('');
    }

    totalRows += rows.length;
  }

  out.push('SET FOREIGN_KEY_CHECKS = 1;');
  out.push('COMMIT;');
  out.push('');

  fs.writeFileSync(OUT, out.join('\n'));

  console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
  console.log(`  ${schemas.length} table(s) created, ${withData.length} with data, ${totalRows} row(s)`);
  if (scrubbed) console.log(`  ${scrubbed} credential value(s) blanked`);
  if (skipped.length) console.log(`  ${skipped.join(', ')}: structure kept, rows skipped (belong to one install)`);

  await db.close();
}

main().catch(async (err) => {
  console.error(err.message);
  await db.close().catch(() => {});
  process.exit(1);
});
